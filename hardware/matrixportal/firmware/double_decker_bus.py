# Works even when sprite x is negative or partly off-screen.
def draw(plot_pixel, x, y, *, display_width=256, display_height=32,
         limited_palette=False, blank_sign=False):
    palette = PALETTE_8 if limited_palette else PALETTE
    data = ROWS_BLANK_SIGN if blank_sign else ROWS
    for dy, row in enumerate(data):
        py = y + dy
        if py < 0 or py >= display_height:
            continue
        for dx, key in enumerate(row):
            if key == ".":
                continue
            px = x + dx
            if 0 <= px < display_width:
                plot_pixel(px, py, palette[key])

# 0 means transparent (clear pixel in a full-frame draw).
PALETTE_INDEX = {".": 0}
for _i, _key in enumerate(PALETTE, 1):
    PALETTE_INDEX[_key] = _i


def draw_indexed(bitmap, x, y, *, display_width=256, display_height=32,
                 blank_sign=False):
    """Draw on an existing indexed displayio.Bitmap without allocation.

    Configure the receiving displayio.Palette to agree with PALETTE_INDEX.
    Clear/redraw the background between animation frames; transparency skips writes.
    """
    data = ROWS_BLANK_SIGN if blank_sign else ROWS
    for dy, row in enumerate(data):
        py = y + dy
        if py < 0 or py >= display_height:
            continue
        for dx, key in enumerate(row):
            px = x + dx
            if key != "." and 0 <= px < display_width:
                bitmap[px, py] = PALETTE_INDEX[key]

