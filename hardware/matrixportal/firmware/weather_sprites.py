def icon_for_wmo(code, is_day=True):
    """Return an icon name for a WMO / Open-Meteo weather_code integer.
    For daytime 0-2 use sun icons; nighttime uses moon variants.
    """
    if code == 0:
        return "sunny" if is_day else "clear_night"
    if code in (1, 2):
        return "partly_cloudy" if is_day else "partly_cloudy_night"
    if code == 3:
        return "overcast"
    if code in (45, 48):
        return "fog"
    if code in (51, 53, 55):
        return "drizzle"
    if code in (56, 57, 66, 67):
        return "sleet"
    if code in (61, 63):
        return "rain"
    if code == 65:
        return "heavy_rain"
    if code in (71, 73, 75, 77, 85, 86):
        return "snow"
    if code in (80, 81):
        return "showers"
    if code == 82:
        return "heavy_rain"
    if code == 95:
        return "thunderstorm"
    if code in (96, 99):
        return "hail"
    return "cloudy"


def draw_sprite(plot_pixel, name, x, y, *, size=14, limited_palette=True,
                clip_width=256, clip_height=32):
    """Render directly using plot_pixel(x, y, rgb_int).

    Drawing is clipped to the display rectangle; '.' never overwrites pixels.
    Call from the existing framebuffer/frame loop. Screen clearing is caller-owned.

    Example: draw_sprite(my_plot_pixel, 'rain', 5, 9)
             draw_sprite(my_plot_pixel, 'moon', 5, 5, size=21)
    """
    sprites = WEATHER_14 if size == 14 else CELESTIAL_21
    palette = PALETTE_8 if limited_palette else PALETTE_RGB
    bitmap = sprites[name]
    for iy, row in enumerate(bitmap):
        py = y + iy
        if py < 0 or py >= clip_height:
            continue
        for ix, key in enumerate(row):
            px = x + ix
            if key != '.' and 0 <= px < clip_width:
                plot_pixel(px, py, palette[key])
