"""MatrixPortal dirty-region refresh benchmark for issue #92.

Copy this file to CIRCUITPY/code.py to compare FramebufferDisplay refresh
duration for differently sized displayio dirty regions. This is intentionally
standalone: no Wi-Fi, HTTP, MQTT, application renderer, or fonts are used.

The benchmark does NOT implement native partial RGBMatrix conversion. It
measures the current CircuitPython stack so we can decide whether such a
change is worth pursuing.
"""

import gc
import time

import board
import displayio
import framebufferio
import rgbmatrix


DISPLAY_WIDTH = 256
DISPLAY_HEIGHT = 32
BIT_DEPTH = 1
WARMUP_ITERATIONS = 12
MEASURE_ITERATIONS = 80
ROUNDS = 3

# Sparse lit pixels keep the full-area test's power draw modest while palette
# mutation still dirties the complete TileGrid area.
COLOR_A = 0xFF0000
COLOR_B = 0x00FF00


def _now():
    if hasattr(time, "monotonic_ns"):
        return time.monotonic_ns(), True
    return time.monotonic(), False


def _elapsed_ms(start, nanoseconds):
    end = time.monotonic_ns() if nanoseconds else time.monotonic()
    if nanoseconds:
        return (end - start) / 1000000.0
    return (end - start) * 1000.0


def _region_scene(width, height, x=0, y=0):
    bitmap = displayio.Bitmap(width, height, 2)
    palette = displayio.Palette(2)
    palette[0] = 0x000000
    palette[1] = COLOR_A

    # A sparse pattern reduces LED current without changing the dirty extent
    # generated by a palette mutation on this TileGrid.
    for py in range(height):
        for px in range(width):
            if (px + py) % 4 == 0:
                bitmap[px, py] = 1

    tile = displayio.TileGrid(bitmap, pixel_shader=palette, x=x, y=y)
    root = displayio.Group()
    root.append(tile)
    return root, palette, tile


def _measure_palette(display, name, width, height, x=0, y=0):
    root, palette, _tile = _region_scene(width, height, x=x, y=y)
    display.root_group = root

    # Root replacement requests a full refresh. Discard it and several
    # subsequent mutations so the measured samples represent steady state.
    display.refresh(target_frames_per_second=None)
    for index in range(WARMUP_ITERATIONS):
        palette[1] = COLOR_A if index % 2 else COLOR_B
        display.refresh(target_frames_per_second=None)

    gc.collect()
    minimum = None
    maximum = 0.0
    total = 0.0
    for index in range(MEASURE_ITERATIONS):
        palette[1] = COLOR_A if index % 2 else COLOR_B
        started, nanoseconds = _now()
        display.refresh(target_frames_per_second=None)
        elapsed = _elapsed_ms(started, nanoseconds)
        total += elapsed
        maximum = max(maximum, elapsed)
        minimum = elapsed if minimum is None else min(minimum, elapsed)

    print(
        "BENCH scenario={} count={} min_ms={:.3f} avg_ms={:.3f} max_ms={:.3f}".format(
            name,
            MEASURE_ITERATIONS,
            minimum or 0.0,
            total / MEASURE_ITERATIONS,
            maximum,
        )
    )


def _measure_move(display, name, width, height, x=112, y=12):
    root, _palette, tile = _region_scene(width, height, x=x, y=y)
    display.root_group = root
    display.refresh(target_frames_per_second=None)

    for index in range(WARMUP_ITERATIONS):
        tile.x = x + (index & 1)
        display.refresh(target_frames_per_second=None)

    gc.collect()
    minimum = None
    maximum = 0.0
    total = 0.0
    for index in range(MEASURE_ITERATIONS):
        tile.x = x + (index & 1)
        started, nanoseconds = _now()
        display.refresh(target_frames_per_second=None)
        elapsed = _elapsed_ms(started, nanoseconds)
        total += elapsed
        maximum = max(maximum, elapsed)
        minimum = elapsed if minimum is None else min(minimum, elapsed)

    print(
        "BENCH scenario={} count={} min_ms={:.3f} avg_ms={:.3f} max_ms={:.3f}".format(
            name,
            MEASURE_ITERATIONS,
            minimum or 0.0,
            total / MEASURE_ITERATIONS,
            maximum,
        )
    )


displayio.release_displays()

matrix = rgbmatrix.RGBMatrix(
    width=DISPLAY_WIDTH,
    height=DISPLAY_HEIGHT,
    bit_depth=BIT_DEPTH,
    doublebuffer=True,
    addr_pins=board.MTX_ADDRESS[:4],
    **board.MTX_COMMON,
)
display = framebufferio.FramebufferDisplay(matrix, auto_refresh=False)

print("MatrixPortal dirty-region refresh benchmark")
print(
    "CONFIG width={} height={} bit_depth={} doublebuffer=True warmup={} samples={} rounds={}".format(
        DISPLAY_WIDTH,
        DISPLAY_HEIGHT,
        BIT_DEPTH,
        WARMUP_ITERATIONS,
        MEASURE_ITERATIONS,
        ROUNDS,
    )
)

scenarios = (
    ("full_256x32", "palette", 256, 32, 0, 0),
    ("band_256x8", "palette", 256, 8, 0, 12),
    ("band_32x8", "palette", 32, 8, 112, 12),
    ("move_32x8_1px", "move", 32, 8, 112, 12),
)

for round_index in range(ROUNDS):
    print("ROUND {}".format(round_index + 1))
    ordered = scenarios if round_index % 2 == 0 else tuple(reversed(scenarios))
    for name, mode, width, height, x, y in ordered:
        if mode == "move":
            _measure_move(display, name, width, height, x=x, y=y)
        else:
            _measure_palette(display, name, width, height, x=x, y=y)

print("BENCH COMPLETE")
while True:
    time.sleep(60)
